def translate_log_line(line: str) -> str:
    for pattern, translation in LOG_TRANSLATIONS.items():
        if pattern in line:
            # Extract timestamp
            ts_match = re.search(r"\[(\d{4}-\d{2}-\d{2} \d{2}:\d{2}:\d{2})\]", line)
            ts = ts_match.group(1) if ts_match else ""
            return f"- {ts} {translation}"
    return ""


