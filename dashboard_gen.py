def get_orch_log_tail(lines: int = 30) -> list[str]:
    try:
        all_lines = ORCH_LOG.read_text(encoding="utf-8", errors="ignore").splitlines()
        return all_lines[-lines:]
    except Exception:
        return []


def get_task_info() -> tuple[str, str]:
    """Return (task_name, goal) from current task file."""
    for path in [TASK_FILE, CURRENT_TASK_FILE]:
        try:
            text = path.read_text(encoding="utf-8", errors="ignore")
            name = goal = ""
            for line in text.splitlines():
                if line.lower().startswith("title:"):
                    name = line.split(":", 1)[1].strip()
                elif line.lower().startswith("goal:"):
                    goal = line.split(":", 1)[1].strip()
            if name:
                return name, goal
        except Exception:
            continue
    return "", ""


