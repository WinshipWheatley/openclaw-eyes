def gen_cassandra() -> str:
    """Generate 'Cassandra.md' — Cassandra status dashboard."""
    state = load_json(CASSANDRA_STATE)
    flags = get_capability_flags()
    procs = get_processes()
    nicknames = load_json(CONTACT_NICKNAMES)
    followups = load_jsonl(FOLLOWUP_LOG)

    lines = [
        "# 🔮 Cassandra — Status Dashboard",
        f"*Updated: {now_str()}*",
        "",
    ]

    # Process status
    cas_procs = procs.get("cassandra", [])
    lines.append("### Processes")
    if cas_procs:
        for p in cas_procs:
            pid = p["pid"]
            cmd = p["line"].split("/")[-1][:60] if "/" in p["line"] else p["line"][:60]
            lines.append(f"- ✅ PID {pid}: `{cmd}`")
    else:
        lines.append("- ❌ No Cassandra processes running!")

    # Capabilities
    lines.extend(["", "### Capabilities"])
    for name, connected in sorted(flags.items()):
        icon = "✅" if connected else "❌"
        lines.append(f"- {icon} {name}: {'Connected' if connected else 'Not connected'}")

    # Last interaction
    last_interaction = state.get("last_interaction_at", "N/A")
    lines.extend([
        "", "### Last Activity",
        f"- Last interaction: {last_interaction} ({age_str(last_interaction) if last_interaction != 'N/A' else 'N/A'})",
    ])

    # Chirp log
    chirps = state.get("chirp_log", [])
    if chirps:
        lines.extend(["", f"### Chirp Log ({len(chirps)} entries)"])
        for c in chirps[-5:]:
            lines.append(f"- {c.get('type', '?')} at {c.get('at', '?')}")

    # Contacts
    lines.extend(["", "### Contacts"])
    placeholder_count = 0
    for nick, data in nicknames.items():
        if nick.startswith("_"):
            continue
        name = data.get("name", str(data)) if isinstance(data, dict) else str(data)
        is_placeholder = "PLACEHOLDER" in str(name)
        if is_placeholder:
            placeholder_count += 1
        icon = "⚠️" if is_placeholder else "✅"
        lines.append(f"- {icon} {nick}: {name[:40]}")
    if placeholder_count:
        lines.append(f"\n**⚠️ {placeholder_count} contacts still have PLACEHOLDER names — outreach blocked**")

    # Follow-ups
    if followups:
        lines.extend(["", f"### Follow-up Queue ({len(followups)})"])
        for f in followups[-5:]:
            lines.append(f"- {f.get('capability', '?')}: {f.get('status', '?')}")

    # Queued Cassandra upgrade tasks
    cas_tasks = [t for t in get_queued_tasks() if t.startswith("cas-")]
    if cas_tasks:
        lines.extend(["", f"### Queued Upgrade Tasks ({len(cas_tasks)})"])
        for t in cas_tasks:
            lines.append(f"- 📋 {t}")

    # Recent conversations — show wins (routed) and fails (error/unrouted) separately
    convos = load_jsonl(CONVERSATIONS_LOG)
    if convos:
        wins = [c for c in convos if c.get("route") not in ("llm", "llm_deep", "error")]
        fallbacks = [c for c in convos if c.get("route") in ("llm", "llm_deep")]
        errors = [c for c in convos if c.get("route") == "error"]
        recent = convos[-10:]
        lines.extend(["", f"### Recent Messages ({len(convos)} total — {len(wins)} routed, {len(fallbacks)} unrouted, {len(errors)} errors)"])
        for c in reversed(recent):
            ts = c.get("ts", "?")
            user_msg = c.get("user", "")[:80]
            route = c.get("route", "?")
            replies = c.get("replies", [])
            reply_preview = replies[0][:80] if replies else ""
            # Visual distinction: routed=✅, unrouted=⚠️, error=❌
            if route in ("llm", "llm_deep"):
                route_icon = "⚠️"
                route_label = f"unrouted ({route})"
            elif route == "error":
                route_icon = "❌"
                route_label = "error"
            else:
                route_icon = "✅"
                route_label = route
            lines.extend([
                f"- **{ts}** {route_icon} [{route_label}]",
                f"  - 👤 {user_msg}",
                f"  - 🔮 {reply_preview}",
            ])

    # Briefing delivery failures (PENDING in briefing_log.md)
    briefing_log = Path("/mnt/c/OpenClaw/logs/cassandra_briefings/briefing_log.md")
    if briefing_log.exists():
        try:
            log_lines = briefing_log.read_text().splitlines()
            pending = [l for l in log_lines if "/PENDING]" in l]
            delivered = [l for l in log_lines if "/delivered]" in l]
            failed_llm = [l for l in log_lines if "LLM did not respond" in l or "unavailable" in l.lower()]
            if pending or failed_llm:
                lines.extend(["", f"### Briefing Delivery Issues"])
                lines.append(f"- Total generated: {len(pending) + len(delivered)}")
                lines.append(f"- Delivered (Telegram): {len(delivered)}")
                lines.append(f"- PENDING (not delivered): {len(pending)}")
                if failed_llm:
                    lines.append(f"- LLM failures during generation: {len(failed_llm)}")
                    for fl in failed_llm[-3:]:
                        lines.append(f"  - {fl.strip()[:100]}")
        except Exception:
            pass

    return "\n".join(lines) + "\n"


def gen_chief() -> str:
    """Generate 'Chief.md' — Chief status dashboard."""
    procs = get_processes()
    chief_procs = procs.get("chief", [])

    lines = [
        "# 🎖️ Chief — Status Dashboard",
        f"*Updated: {now_str()}*",
        "",
        "### Processes",
    ]

    expected = [
        "chief_listener.py",
        "chief_worker.py",
        "chief_memory_worker.py",
        "chief_state_worker.py",
        "chief_watcher_brain.py",
    ]

    running_names = set()
    for p in chief_procs:
        for name in expected:
            if name in p["line"]:
                running_names.add(name)

    for name in expected:
        if name in running_names:
            lines.append(f"- ✅ {name}")
        else:
            lines.append(f"- ❌ {name} — NOT RUNNING")

    # Also show other chief processes
    others = [p for p in chief_procs if not any(e in p["line"] for e in expected)]
    if others:
        lines.append("")
        lines.append("### Other Chief Processes")
        for p in others:
            cmd = p["line"].split("/")[-1][:60] if "/" in p["line"] else p["line"][:60]
            lines.append(f"- PID {p['pid']}: `{cmd}`")

    # Builder status
    builder_procs = procs.get("builder", [])
    lines.extend(["", "### Builder"])
    if builder_procs:
        for p in builder_procs:
            lines.append(f"- ✅ PID {p['pid']}: running")
    else:
        lines.append("- ⬜ No builder process running (normal when idle)")

    # Ollama
    lines.extend(["", "### Ollama Models"])
    try:
        out = subprocess.check_output(
            ["curl", "-s", "http://localhost:11434/api/tags"],
            text=True, timeout=5
        )
        models = json.loads(out).get("models", [])
        for m in models:
            lines.append(f"- {m['name']}")
    except Exception:
        lines.append("- ❌ Ollama not reachable")

    return "\n".join(lines) + "\n"


